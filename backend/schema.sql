CREATE TABLE IF NOT EXISTS complaint (
    complaint_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    issue_type VARCHAR(255),
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    student_id VARCHAR(20) NOT NULL REFERENCES student(student_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    department_id INTEGER NOT NULL REFERENCES department(department_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS complaint_status (
    status_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status VARCHAR(20) NOT NULL CHECK (status IN ('Pending', 'In Progress', 'Resolved', 'Rejected')),
    remarks VARCHAR(500),
    updated_by INTEGER NOT NULL REFERENCES admin(admin_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    complaint_id INTEGER NOT NULL REFERENCES complaint(complaint_id)
        ON UPDATE CASCADE ON DELETE CASCADE
);
